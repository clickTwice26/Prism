// Command signtemplates parses the IsharaKotha sign corpus into recognition
// templates and writes them, with a coverage report, for review.
//
//	go run ./cmd/signtemplates -dir ../data/isharakotha/raw/extracted -out ../data/isharakotha
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/clickTwice26/Prism/backend/internal/signref"
)

func main() {
	dir := flag.String("dir", "../data/isharakotha/raw/extracted", "extracted IsharaKotha corpus")
	out := flag.String("out", "../data/isharakotha", "where to write templates.json and report.md")
	flag.Parse()

	idx := signref.Load(*dir)
	if idx.Size() == 0 {
		log.Fatalf("no .sigml files found under %s", *dir)
	}
	if err := os.MkdirAll(*out, 0o755); err != nil {
		log.Fatal(err)
	}
	write := func(name string, v any) {
		raw, err := json.MarshalIndent(v, "", " ")
		if err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(*out, name), raw, 0o644); err != nil {
			log.Fatal(err)
		}
	}
	write("templates.json", idx.Templates("", nil))
	write("failures.json", idx.Failures())
	st := idx.Stats()
	write("stats.json", st)

	if err := os.WriteFile(filepath.Join(*out, "report.md"), []byte(report(st, idx)), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d files: %d parsed (%d complete), %d failed. Wrote %s\n",
		st.Files, st.Parsed, st.Complete, st.Failed, *out)
}

func top(m map[string]int, n int) string {
	type kv struct {
		k string
		v int
	}
	var xs []kv
	for k, v := range m {
		xs = append(xs, kv{k, v})
	}
	sort.Slice(xs, func(i, j int) bool { return xs[i].v > xs[j].v || (xs[i].v == xs[j].v && xs[i].k < xs[j].k) })
	if n > 0 && len(xs) > n {
		xs = xs[:n]
	}
	var b strings.Builder
	for _, x := range xs {
		fmt.Fprintf(&b, "| %s | %d |\n", x.k, x.v)
	}
	return b.String()
}

func report(st signref.Stats, idx *signref.Index) string {
	var b strings.Builder
	pct := func(a, b int) float64 { return 100 * float64(a) / float64(max(b, 1)) }
	fmt.Fprintf(&b, "# IsharaKotha sign templates: coverage report\n\n")
	fmt.Fprintf(&b, "Generated by `go run ./cmd/signtemplates`. See docs/sign-recognition-plan.md.\n\n")
	fmt.Fprintf(&b, "| Measure | Count |\n| --- | --- |\n")
	fmt.Fprintf(&b, "| Corpus files | %d |\n| Parsed | %d (%.1f%%) |\n| Complete (handshape, orientation, location) | %d (%.1f%% of files) |\n",
		st.Files, st.Parsed, pct(st.Parsed, st.Files), st.Complete, pct(st.Complete, st.Files))
	fmt.Fprintf(&b, "| Unique words parsed | %d |\n| Unique words complete | %d |\n| Failed to read | %d |\n",
		st.UniqueWords, st.CompleteWord, st.Failed)
	fmt.Fprintf(&b, "| Signs | %d |\n| Words made of several signs | %d |\n| Words with unplaced symbols | %d |\n| Signs with non-manual features | %d |\n\n",
		st.Signs, st.MultiSign, st.WithGaps, st.NonManual)
	fmt.Fprintf(&b, "## Hands\n\n| Hands | Signs |\n| --- | --- |\n%s\n", top(st.Hands, 0))
	fmt.Fprintf(&b, "## Handshapes (dominant hand)\n\n| Handshape | Signs |\n| --- | --- |\n%s\n", top(st.Handshapes, 0))
	fmt.Fprintf(&b, "## Actions\n\n| Kind | Count |\n| --- | --- |\n%s\n", top(st.ActionKinds, 0))
	fmt.Fprintf(&b, "## Complete words by section\n\n| Section | Words |\n| --- | --- |\n%s\n", top(st.BySection, 0))
	fmt.Fprintf(&b, "## Symbols the parser could not place\n\n| Symbol | Count |\n| --- | --- |\n%s\n", top(st.GapSymbols, 30))
	fmt.Fprintf(&b, "## Files that could not be read\n\n| Reason | Files |\n| --- | --- |\n%s\n", top(st.FailReasons, 0))
	b.WriteString("| File | Reason |\n| --- | --- |\n")
	for _, f := range idx.Failures() {
		fmt.Fprintf(&b, "| %s | %s |\n", f.ID, f.Reason)
	}
	return b.String()
}
